create extension if not exists pg_net;

create table if not exists public.push_tokens (
  id bigint generated by default as identity primary key,
  student_id bigint not null,
  expo_push_token text not null unique,
  platform text not null,
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.push_tokens enable row level security;

drop policy if exists "Students manage their push tokens" on public.push_tokens;
create policy "Students manage their push tokens"
on public.push_tokens
for all
to authenticated
using (
  student_id = (
    select s.id from public.student s where s.auth_id = auth.uid() limit 1
  )
)
with check (
  student_id = (
    select s.id from public.student s where s.auth_id = auth.uid() limit 1
  )
);

create or replace function public.send_calendar_push()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  payload jsonb;
begin
  select coalesce(jsonb_agg(
    jsonb_build_object(
      'to', pt.expo_push_token,
      'title', 'Calendar Event Posted',
      'body', coalesce(new.title, 'A new calendar event is available'),
      'sound', 'default',
      'channelId', 'default',
      'data', jsonb_build_object('route', '/calendar')
    )
  ), '[]'::jsonb)
  into payload
  from public.push_tokens pt
  where pt.enabled = true;

  if payload <> '[]'::jsonb then
    perform net.http_post(
      url := 'https://exp.host/--/api/v2/push/send',
      headers := '{"Content-Type":"application/json"}'::jsonb,
      body := payload
    );
  end if;
  return new;
end;
$$;

drop trigger if exists calendar_event_push_trigger on public.calendar_events;
create trigger calendar_event_push_trigger
after insert on public.calendar_events
for each row execute function public.send_calendar_push();

